const floatBits = new DataView(new ArrayBuffer(4));
function bits(value: number): string {
  floatBits.setFloat32(0, value);
  return floatBits.getUint32(0).toString(16).padStart(8, "0");
}

function verifyOracle(converter: ReturnType<typeof createComposeFontScale>, row: OracleRow) {
  const [fontScale, density, encoded] = row, expected = encoded.split(" ");
  const actual = SP_VALUES.map(sp => bits(converter.spToPx(sp, density, fontScale)));
  for (const [fontSp, lineSp] of LINE_PAIRS) {
    const fontPx = converter.spToPx(fontSp, density, fontScale);
    actual.push(bits(converter.dpToSp(Math.fround(fontPx / density), fontScale)));
    actual.push(bits(converter.lineHeightPx(lineSp, fontPx, density, fontScale)));
  }
  expect(actual.length).toBe(expected.length);
  for (let index = 0; index < expected.length; index++) expect(actual[index]).toBe(expected[index]);
}

for (const row of CANONICAL) {
  test(`real Compose 1.7.1 Float oracle: fontScale=${row[0]}, density=${row[1]}`, () => {
    verifyOracle(createComposeFontScale(), row);
  });
}

for (const history of HISTORY) {
  const scales = [...new Set(history.map(row => row[0]))].join(" -> ");
  test(`real Compose 1.7.1 cached table history: ${scales}`, () => {
    const converter = createComposeFontScale();
    for (const row of history) verifyOracle(converter, row);
  });
}

test("Title, inverse line height, then subtitle stay stable in one configured cache", () => {
  // The JVM oracle was also executed in this production order, twice on each
  // Density instance; its bits match the canonical samples recorded above.
  for (const row of CANONICAL.filter(row => row[1] !== 1)) {
    const [scale, density, encoded] = row, expected = encoded.split(" ");
    const converter = createComposeFontScale();
    for (let repeat = 0; repeat < 2; repeat++) {
      const titlePx = converter.spToPx(21, density, scale);
      expect(bits(titlePx)).toBe(expected[2]);
      expect(bits(converter.lineHeightPx(26, titlePx, density, scale))).toBe(expected[15]);
      const subtitlePx = converter.spToPx(12, density, scale);
      expect(bits(subtitlePx)).toBe(expected[0]);
      expect(bits(converter.lineHeightPx(14, subtitlePx, density, scale))).toBe(expected[13]);
    }
  }
});

test("line-height conversion retains the measured inverse Float", () => {
  // Genuine AAR results at 1.075: converting the painted size back to SP gives
  // 21.000001907348633, so replacing the inverse with the original 21 is wrong.
  const converter = createComposeFontScale();
  const fontPx = converter.spToPx(21, 1, 1.075);
  expect(bits(fontPx)).toBe("41ae999a");
  expect(bits(converter.dpToSp(fontPx, 1.075))).toBe("41a80001");
  expect(bits(converter.lineHeightPx(26, fontPx, 1, 1.075))).toBe("41d82be2");
});

test("application exports match the AAR without depending on shared cache history", () => {
  // 1.3 is an original table, so unrelated module consumers cannot change it.
  const fontPx = composeSpToPx(21, 1.75, 1.3);
  expect(bits(fontPx)).toBe("422a1999");
  expect(bits(composeDpToSp(Math.fround(fontPx / 1.75), 1.3))).toBe("41a7ffff");
  expect(bits(composeLineHeightPx(26, fontPx, 1.75, 1.3))).toBe("4252999b");
});


